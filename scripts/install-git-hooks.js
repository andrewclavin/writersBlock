#!/usr/bin/env node
/* eslint-disable no-console */

const fs = require("fs");
const path = require("path");
const { execSync } = require("child_process");

function getRepoRoot() {
  return execSync("git rev-parse --show-toplevel", { encoding: "utf8" }).trim();
}

function ensureDir(p) {
  fs.mkdirSync(p, { recursive: true });
}

function writeExecutable(filePath, content) {
  fs.writeFileSync(filePath, content, { encoding: "utf8" });
  try {
    fs.chmodSync(filePath, 0o755);
  } catch {
    // Best-effort (Windows / restricted FS).
  }
}

/** Shell snippet: Git hooks get a minimal PATH (no nvm/fnm/Homebrew). */
function bootstrappedInvoke(scriptRel) {
  const script = JSON.stringify(scriptRel);
  return `# Git hook: ensure Node on PATH (nvm/fnm/Homebrew)
PATH="/opt/homebrew/bin:/usr/local/bin:\${PATH:-}"
export PATH

if [ -s "\${HOME}/.nvm/nvm.sh" ]; then
  . "\${HOME}/.nvm/nvm.sh"
fi

if [ -x "\${HOME}/.local/share/fnm/aliases/default/bin/node" ] && ! command -v node >/dev/null 2>&1; then
  PATH="\${HOME}/.local/share/fnm/aliases/default/bin:\${PATH}"
  export PATH
fi

if ! command -v node >/dev/null 2>&1; then
  echo "pre-commit: node not found (Git hooks use a minimal PATH). Install Node or run: node scripts/install-git-hooks.js" >&2
  exit 1
fi

exec node ${script}`;
}

function upgradeLegacyHook(existing, scriptRel, invokeBlock, fullHook) {
  const mergedMarker = "\n\n# Added by Writer's Block\n";
  const marker = "Git hook: ensure Node on PATH";

  if (existing.includes(marker)) {
    return existing;
  }

  if (existing.includes(mergedMarker)) {
    const i = existing.lastIndexOf(mergedMarker);
    const base = existing.slice(0, i);
    return `${base}${mergedMarker}${invokeBlock}\n`;
  }

  if (existing.includes("Auto-generated by scripts/install-git-hooks.js")) {
    return fullHook;
  }

  return existing
    .split("\n")
    .flatMap((line) =>
      line.includes(scriptRel) ? invokeBlock.split("\n") : [line],
    )
    .join("\n");
}

function main() {
  let repoRoot;
  try {
    repoRoot = getRepoRoot();
  } catch {
    // Not a git repo; nothing to do.
    process.exit(0);
  }

  const hooksDir = path.join(repoRoot, ".git", "hooks");
  ensureDir(hooksDir);

  const hookPath = path.join(hooksDir, "pre-commit");
  const scriptRel = "scripts/check-local-only-staged.js";
  const invokeBlock = bootstrappedInvoke(scriptRel);
  const hook = `#!/bin/sh
set -e

# Auto-generated by scripts/install-git-hooks.js
# Blocks committing local-only/copyrighted content based on local-only.json.

${invokeBlock}
`;

  // If there is an existing hook, don't clobber it; append our call if missing.
  if (fs.existsSync(hookPath)) {
    let existing = fs.readFileSync(hookPath, "utf8");
    if (existing.includes(scriptRel)) {
      const next = upgradeLegacyHook(existing, scriptRel, invokeBlock, hook);
      if (next !== existing) {
        writeExecutable(hookPath, next);
      }
      process.exit(0);
    }
    const merged = `${existing.trimEnd()}\n\n# Added by Writer's Block\n${invokeBlock}\n`;
    writeExecutable(hookPath, merged);
    process.exit(0);
  }

  writeExecutable(hookPath, hook);
}

main();
